import math

def haversine_m(lat1, lon1, lat2, lon2):
    R = 6_371_000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp/2)**2 + math.cos(p1)*math.cos(p2)*math.sin(dl/2)**2
    return 2 * R * math.asin(math.sqrt(a))

def closest_pt_on_segment(p, a, b):
    dx = b[1] - a[1]
    dy = b[0] - a[0]
    len_sq = dx*dx + dy*dy
    if len_sq == 0:
        return a
    t = ((p[1]-a[1])*dx + (p[0]-a[0])*dy) / len_sq
    t = max(0.0, min(1.0, t))
    return (a[0] + t*dy, a[1] + t*dx)

def closest_pt_on_road(rsu_lat, rsu_lon, road):
    p = (rsu_lat, rsu_lon)
    best_dist = float('inf')
    best_pt = road[0]
    for i in range(len(road) - 1):
        c = closest_pt_on_segment(p, road[i], road[i+1])
        d = haversine_m(p[0], p[1], c[0], c[1])
        if d < best_dist:
            best_dist = d
            best_pt = c
    return best_pt, round(best_dist)

